// Same tip all day (stable), different tomorrow.
export function tipForDay(lang: string, now = new Date()): string {
  const list = COACH_TIPS[(lang as TipLang) in COACH_TIPS ? (lang as TipLang) : 'en'];
  const dayNumber = Math.floor(now.getTime() / 86_400_000);
  return list[dayNumber % list.length];
}
